/**
 * Resolves the exact Print Sheet tiling layout (columns, rows, total photos, bleed)
 * for any photo preset and sheet size ('4x6_in' | '5x7_in' | 'a4_sheet').
 */
export function resolvePrintSheetLayout(
  preset: PhotoPresetSpec,
  sheetSize: PrintSheetSizeId
): {
  sheetName: string;
  sheetWidthMm: number;
  sheetHeightMm: number;
  sheetWidthPx300Dpi: number;
  sheetHeightPx300Dpi: number;
  columns: number;
  rows: number;
  totalPhotos: number;
  gridLabel: string;
  bleedMm: number;
} {
  let groupKey = 'standard_35x45';
  if (preset.widthMm === 51 && preset.heightMm === 51) {
    groupKey = 'square_51x51';
  } else if (
    (preset.widthMm === 25 && preset.heightMm === 35) ||
    (preset.widthMm === 35 && preset.heightMm === 25)
  ) {
    groupKey = 'pan_35x25';
  } else if (preset.widthMm === 20 && preset.heightMm === 25) {
    groupKey = 'stamp_20x25';
  } else if (preset.widthMm >= 50 && preset.heightMm >= 60) {
    groupKey = 'canada_50x70';
  }

  const rule =
    PRINT_SHEET_CAPACITY_RULES.find((r) => r.tileGroup === groupKey) ||
    PRINT_SHEET_CAPACITY_RULES[0];
  const sheetSpec = rule.sheets[sheetSize];

  const dimensionsMap: Record<
    PrintSheetSizeId,
    { wMm: number; hMm: number; wPx: number; hPx: number }
  > = {
    '4x6_in': { wMm: 152.4, hMm: 101.6, wPx: 1800, hPx: 1200 },
    '5x7_in': { wMm: 177.8, hMm: 127.0, wPx: 2100, hPx: 1500 },
    a4_sheet: { wMm: 210.0, hMm: 297.0, wPx: 2480, hPx: 3508 },
  };

  const dims = dimensionsMap[sheetSize];
  return {
    sheetName: sheetSpec.sheetName,
    sheetWidthMm: dims.wMm,
    sheetHeightMm: dims.hMm,
    sheetWidthPx300Dpi: dims.wPx,
    sheetHeightPx300Dpi: dims.hPx,
    columns: sheetSpec.columns,
    rows: sheetSpec.rows,
    totalPhotos: sheetSpec.totalPhotos,
    gridLabel: sheetSpec.gridLabel,
    bleedMm: 2.5,
  };
}
