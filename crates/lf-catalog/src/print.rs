//! Official ID, Passport & Exam Photo Preset Catalog & Print Sheet Tiling Specifications (300 DPI)
//! Covers Category 1 (India National Identity & Passports), Category 2 (India State PSC & National Exams),
//! and Category 3 (International Passport & Visa Photo Sizes).

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PresetCategory {
    IndiaNationalIdAndPassports,
    IndiaStatePscAndNationalExams,
    InternationalPassportsAndVisas,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BiometricStandard {
    UsIndiaSquare51x51,
    IcaoSchengen35x45,
    Uk35x45,
    Canada50x70,
    China33x48,
    PanStampGeneral,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PrintSheetSize {
    Sheet4x6In, // 102 x 152 mm (1800 x 1200 px @ 300 DPI)
    Sheet5x7In, // 127 x 178 mm (2100 x 1500 px @ 300 DPI)
    SheetA4,    // 210 x 297 mm (2480 x 3508 px @ 300 DPI)
}

#[derive(Debug, Clone)]
pub struct OfficialPhotoPreset {
    pub id: &'static str,
    pub category: PresetCategory,
    pub name: &'static str,
    pub authority: &'static str,
    pub width_mm: f32,
    pub height_mm: f32,
    pub width_px_300dpi: u32,
    pub height_px_300dpi: u32,
    pub min_kb: u32,
    pub max_kb: u32,
    pub default_bg_hex: &'static str,
    pub background_rule: &'static str,
    pub face_coverage_rule: &'static str,
    pub biometric_standard: BiometricStandard,
    pub requires_name_date_slate: bool,
    pub supports_signature_box: bool,
    pub requires_back_stamp: bool,
    pub prohibits_glasses: bool,
}

#[derive(Debug, Clone, Copy)]
pub struct PrintSheetGridSpec {
    pub sheet: PrintSheetSize,
    pub columns: u32,
    pub rows: u32,
    pub total_photos: u32,
    pub bleed_mm: f32,
}

impl OfficialPhotoPreset {
    /// Resolves the exact 300 DPI print sheet tiling layout (`4x6 in`, `5x7 in`, `A4 Sheet`)
    /// with 2.5 mm cutting bleed.
    pub fn resolve_sheet_grid(&self, sheet: PrintSheetSize) -> PrintSheetGridSpec {
        let (columns, rows) = if (self.width_mm - 51.0).abs() < 0.5 && (self.height_mm - 51.0).abs() < 0.5 {
            // India / US Square (51 x 51 mm / 2x2 in): 4x6 = 4 (2x2), 5x7 = 6 (2x3), A4 = 15 (3x5)
            match sheet {
                PrintSheetSize::Sheet4x6In => (2, 2),
                PrintSheetSize::Sheet5x7In => (2, 3),
                PrintSheetSize::SheetA4 => (3, 5),
            }
        } else if (self.width_mm - 25.0).abs() < 0.5 && (self.height_mm - 35.0).abs() < 0.5 {
            // PAN Card Size (35 x 25 mm): 4x6 = 12 (3x4), 5x7 = 18 (3x6), A4 = 45 (5x9)
            match sheet {
                PrintSheetSize::Sheet4x6In => (3, 4),
                PrintSheetSize::Sheet5x7In => (3, 6),
                PrintSheetSize::SheetA4 => (5, 9),
            }
        } else if (self.width_mm - 20.0).abs() < 0.5 && (self.height_mm - 25.0).abs() < 0.5 {
            // Indian Stamp Size (20 x 25 mm): 4x6 = 24 (4x6), 5x7 = 35 (5x7), A4 = 90 (9x10)
            match sheet {
                PrintSheetSize::Sheet4x6In => (4, 6),
                PrintSheetSize::Sheet5x7In => (5, 7),
                PrintSheetSize::SheetA4 => (9, 10),
            }
        } else if self.width_mm >= 50.0 && self.height_mm >= 60.0 {
            // Canada Passport / PR (50 x 70 mm): 4x6 = 4 (2x2), 5x7 = 4 (2x2), A4 = 12 (3x4)
            match sheet {
                PrintSheetSize::Sheet4x6In => (2, 2),
                PrintSheetSize::Sheet5x7In => (2, 2),
                PrintSheetSize::SheetA4 => (3, 4),
            }
        } else {
            // Standard Passport (35 x 45 mm): 4x6 = 8 (4x2), 5x7 = 12 (4x3), A4 = 30 (5x6)
            match sheet {
                PrintSheetSize::Sheet4x6In => (4, 2),
                PrintSheetSize::Sheet5x7In => (4, 3),
                PrintSheetSize::SheetA4 => (5, 6),
            }
        };

        PrintSheetGridSpec {
            sheet,
            columns,
            rows,
            total_photos: columns * rows,
            bleed_mm: 2.5,
        }
    }
}

